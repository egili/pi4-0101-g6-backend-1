package cofre.repository;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.TestPropertySource;

import java.sql.Timestamp;
import java.time.LocalDateTime;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

@SpringBootTest
@TestPropertySource(properties = {
        "servidor.porta=0",
        "servidor.comandos=false",
        "jwt.secret=chave-de-teste-do-cofre-com-mais-de-32-caracteres",
        "jwt.expiration=86400"
})
public class AtualizacaoCredencialTest {

    @Autowired
    private CredentialRepository repositorio;

    @Autowired
    private JdbcTemplate jdbc;

    @BeforeEach
    public void criaTabelaCredencial() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS credencial (" +
                "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "usuario_id BIGINT NOT NULL REFERENCES usuario(id), " +
                "servico VARCHAR(255) NOT NULL, " +
                "usuario_servico VARCHAR(255) NOT NULL, " +
                "dados_cifrados VARCHAR(4096) NOT NULL, " +
                "iv VARCHAR(255) NOT NULL, " +
                "criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, " +
                "atualizado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)");
    }

    @Test
    public void atualizarGravaAtualizadoEm() {
        jdbc.update("INSERT INTO usuario (username, senha_mestra_hash, salt) VALUES (?, ?, ?)",
                "atualiza" + System.nanoTime(), "h", "s");
        Long usuarioId = jdbc.queryForObject("SELECT MAX(id) FROM usuario", Long.class);
        jdbc.update("INSERT INTO credencial (usuario_id, servico, usuario_servico, dados_cifrados, iv, criado_em, atualizado_em) " +
                "VALUES (?, 'Gmail', 'a@b.c', 'DADOS', 'IV', ?, ?)",
                usuarioId, Timestamp.valueOf(LocalDateTime.of(2020, 1, 1, 0, 0)), Timestamp.valueOf(LocalDateTime.of(2020, 1, 1, 0, 0)));
        Long credencialId = jdbc.queryForObject("SELECT MAX(id) FROM credencial", Long.class);

        repositorio.atualizar(credencialId, "Gmail", "a@b.c", "NOVOS-DADOS", "NOVO-IV");

        Timestamp atualizado = jdbc.queryForObject("SELECT atualizado_em FROM credencial WHERE id = ?", Timestamp.class, credencialId);
        Timestamp criado = jdbc.queryForObject("SELECT criado_em FROM credencial WHERE id = ?", Timestamp.class, credencialId);
        String dados = jdbc.queryForObject("SELECT dados_cifrados FROM credencial WHERE id = ?", String.class, credencialId);
        assertEquals("NOVOS-DADOS", dados);
        assertTrue(atualizado.after(Timestamp.valueOf(LocalDateTime.of(2020, 1, 2, 0, 0))),
                "atualizado_em deve ser a data da alteração, não a de criação");
        assertEquals(Timestamp.valueOf(LocalDateTime.of(2020, 1, 1, 0, 0)), criado, "criado_em não muda na alteração");
    }
}
