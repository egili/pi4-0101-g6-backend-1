package cofre.rede;

import cofre.protocolo.ComunicadoDeDesligamento;
import cofre.protocolo.CredencialDto;
import cofre.protocolo.Comunicado;
import cofre.protocolo.Parceiro;
import cofre.protocolo.PedidoDeAtualizacao;
import cofre.protocolo.PedidoDeCadastro;
import cofre.protocolo.PedidoDeCriacao;
import cofre.protocolo.PedidoDeExclusao;
import cofre.protocolo.PedidoDeExportacao;
import cofre.protocolo.PedidoDeImportacao;
import cofre.protocolo.PedidoDeListagem;
import cofre.protocolo.PedidoDeLogin;
import cofre.protocolo.PedidoDeSalt;
import cofre.protocolo.PedidoParaSair;
import cofre.protocolo.Resposta;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.TestPropertySource;

import java.io.IOException;
import java.io.ObjectInputStream;
import java.io.ObjectOutputStream;
import java.net.Socket;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.concurrent.Callable;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
@TestPropertySource(properties = {
        "servidor.porta=0",
        "jwt.secret=chave-de-teste-do-cofre-com-mais-de-32-caracteres",
        "jwt.expiration=86400"
})
public class SocketServidorTest {

    @Autowired
    private ServidorSocket servidor;

    @Autowired
    private JdbcTemplate jdbc;

    @BeforeEach
    public void criaTabelaCredencial() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS credencial (" +
                "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "usuario_id BIGINT NOT NULL REFERENCES usuario(id), " +
                "servico VARCHAR(255) NOT NULL, " +
                "usuario_servico VARCHAR(255) NOT NULL, " +
                "dados_cifrados VARCHAR(4096) NOT NULL, " +
                "iv VARCHAR(255) NOT NULL)");
    }

    @Test
    public void cadastroSaltLoginECredenciaisPeloSocket() throws Exception {
        Parceiro c = conectar();
        String u = "sock" + System.nanoTime();

        Resposta cadastro = pedir(c, new PedidoDeCadastro(u, "hash-1", "salt-1"));
        assertTrue(cadastro.ok());
        assertNotNull(cadastro.getDados().get("usuarioId"));
        assertEquals("USUARIO_JA_EXISTE", pedir(c, new PedidoDeCadastro(u, "hash-1", "salt-1")).getErro());

        assertEquals("salt-1", pedir(c, new PedidoDeSalt(u)).getDados().get("salt"));
        assertEquals(pedir(c, new PedidoDeSalt("ninguem-" + u)).getDados().get("salt"),
                pedir(c, new PedidoDeSalt("ninguem-" + u)).getDados().get("salt"), "salt falso deve ser estável");

        assertEquals("SENHA_INCORRETA", pedir(c, new PedidoDeLogin(u, "errado")).getErro());
        String token = (String) pedir(c, new PedidoDeLogin(u, "hash-1")).getDados().get("token");
        assertNotNull(token);

        Resposta criada = pedir(c, new PedidoDeCriacao(token, "Gmail", "eli@gmail.com", "DADOS-1", "IV-1"));
        assertTrue(criada.ok());
        long id = ((Number) criada.getDados().get("credencialId")).longValue();

        List<CredencialDto> lista = credenciais(pedir(c, new PedidoDeListagem(token)));
        assertEquals(1, lista.size());
        assertEquals("DADOS-1", lista.get(0).getDadosCifrados());

        assertTrue(pedir(c, new PedidoDeAtualizacao(token, id, "Gmail", "eli@gmail.com", "DADOS-2", "IV-2")).ok());
        assertTrue(pedir(c, new PedidoDeExclusao(token, id)).ok());
        assertEquals(0, credenciais(pedir(c, new PedidoDeListagem(token))).size());

        assertEquals("BACKUP_VAZIO", pedir(c, new PedidoDeExportacao(token)).getErro());
        List<CredencialDto> importar = new ArrayList<>();
        importar.add(new CredencialDto(null, "GitHub", "eli", "DADOS-3", "IV-3"));
        assertEquals(1, pedir(c, new PedidoDeImportacao(token, importar)).getDados().get("credenciaisInseridas"));
        assertEquals(1, credenciais(pedir(c, new PedidoDeExportacao(token))).size());

        assertEquals("SESSAO_INVALIDA", pedir(c, new PedidoDeListagem("token-falso")).getErro());
        sair(c);
    }

    @Test
    public void conexaoOciosaNaoBloqueiaOutroCliente() throws Exception {
        Parceiro ocioso = conectar();
        Parceiro ativo = conectar();
        String u = "par" + System.nanoTime();
        pedir(ativo, new PedidoDeCadastro(u, "h", "s"));

        ExecutorService pool = Executors.newFixedThreadPool(1);
        try {
            Future<Resposta> futuro = pool.submit((Callable<Resposta>) () -> pedir(ativo, new PedidoDeSalt(u)));
            assertEquals("s", futuro.get(5, java.util.concurrent.TimeUnit.SECONDS).getDados().get("salt"));
        } finally {
            pool.shutdownNow();
        }
        sair(ativo);
        sair(ocioso);
    }

    @Test
    public void desligamentoAvisaTodosOsClientesConectados() throws Exception {
        Parceiro a = conectar();
        Parceiro b = conectar();
        pedir(a, new PedidoDeSalt("qualquer"));
        pedir(b, new PedidoDeSalt("qualquer"));

        servidor.avisarDesligamento();

        assertTrue(a.envie() instanceof ComunicadoDeDesligamento);
        assertTrue(b.envie() instanceof ComunicadoDeDesligamento);
        a.adeus();
        b.adeus();
    }

    @Test
    public void doisClientesEnviamPedidosAoMesmoTempo() throws Exception {
        ExecutorService pool = Executors.newFixedThreadPool(2);
        try {
            List<Future<Boolean>> resultados = new ArrayList<>();
            for (int k = 0; k < 2; k++) {
                final int cliente = k;
                Callable<Boolean> tarefa = () -> {
                    Parceiro c = conectar();
                    boolean tudoCerto = true;
                    for (int j = 0; j < 20; j++) {
                        String usuario = "carga" + cliente + "-" + j + "-" + System.nanoTime();
                        tudoCerto &= pedir(c, new PedidoDeCadastro(usuario, "h", "s")).ok();
                        tudoCerto &= pedir(c, new PedidoDeSalt(usuario)).ok();
                    }
                    sair(c);
                    return tudoCerto;
                };
                resultados.add(pool.submit(tarefa));
            }
            for (Future<Boolean> r : resultados) {
                assertTrue(r.get(60, TimeUnit.SECONDS));
            }
        } finally {
            pool.shutdownNow();
        }
    }

    private Parceiro conectar() throws IOException {
        Socket s = new Socket("localhost", servidor.getPorta());
        ObjectOutputStream transmissor = new ObjectOutputStream(s.getOutputStream());
        transmissor.flush();
        ObjectInputStream receptor = Parceiro.novoReceptor(s.getInputStream());
        return new Parceiro(s, receptor, transmissor);
    }

    private static Resposta pedir(Parceiro c, Comunicado pedido) throws Exception {
        c.receba(pedido);
        return (Resposta) c.envie();
    }

    @SuppressWarnings("unchecked")
    private static List<CredencialDto> credenciais(Resposta r) {
        return (List<CredencialDto>) r.getDados().get("credenciais");
    }

    private static void sair(Parceiro c) throws IOException {
        c.receba(new PedidoParaSair());
        c.adeus();
    }
}
