package cofre;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.client.TestRestTemplate;
import org.springframework.http.HttpEntity;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpMethod;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.TestPropertySource;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;

// Tabela credencial em DDL do H2: a entidade não existe no Servidor, então o teste cria a tabela
@TestPropertySource(properties = {
        "jwt.secret=chave-de-teste-do-cofre-com-mais-de-32-caracteres",
        "jwt.expiration=86400000"
})
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
public class BackupControllerTest {

    @Autowired
    private TestRestTemplate restTemplate;

    @Autowired
    private JdbcTemplate jdbc;

    @Autowired
    private JwtService jwtService;

    @BeforeEach
    public void criaTabelaCredencial() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS credencial (" +
                "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "usuario_id BIGINT NOT NULL REFERENCES usuario(id), " +
                "servico VARCHAR(255) NOT NULL, " +
                "usuario_servico VARCHAR(255) NOT NULL, " +
                "dados_cifrados VARCHAR(4096) NOT NULL, " +
                "iv VARCHAR(255) NOT NULL)");
        jdbc.execute("DELETE FROM credencial");
    }

    @Test
    public void recusaRequisicaoSemToken() {
        ResponseEntity<Map> resposta = restTemplate.getForEntity("/backup", Map.class);

        assertEquals(HttpStatus.UNAUTHORIZED, resposta.getStatusCode());
        assertEquals("SESSAO_INVALIDA", resposta.getBody().get("erro"));
    }

    @Test
    public void devolveCredenciaisCifradasESalt() {
        long id = criarUsuario("bk.ana");
        jdbc.update("INSERT INTO credencial (usuario_id, servico, usuario_servico, dados_cifrados, iv) VALUES (?, ?, ?, ?, ?)",
                id, "Gmail", "ana@gmail.com", "dados-cifrados", "iv-1");

        ResponseEntity<Map> resposta = restTemplate.exchange("/backup", HttpMethod.GET, comToken(id, "bk.ana"), Map.class);

        assertEquals(HttpStatus.OK, resposta.getStatusCode());
        List<Map<String, Object>> credenciais = (List<Map<String, Object>>) resposta.getBody().get("credenciais");
        assertEquals(1, credenciais.size());
        assertEquals("dados-cifrados", credenciais.get(0).get("dadosCifrados"));
        Map<String, Object> usuario = (Map<String, Object>) resposta.getBody().get("usuario");
        assertEquals("salt-bk.ana", usuario.get("salt"));
    }

    @Test
    public void recusaBackupDeUsuarioSemCredenciais() {
        long id = criarUsuario("bk.vazio");

        ResponseEntity<Map> resposta = restTemplate.exchange("/backup", HttpMethod.GET, comToken(id, "bk.vazio"), Map.class);

        assertEquals(HttpStatus.NOT_FOUND, resposta.getStatusCode());
        assertEquals("BACKUP_VAZIO", resposta.getBody().get("erro"));
    }

    @Test
    public void recusaImportacaoSemToken() {
        ResponseEntity<Map> resposta = restTemplate.postForEntity("/backup", List.of(itemValido("Gmail")), Map.class);

        assertEquals(HttpStatus.UNAUTHORIZED, resposta.getStatusCode());
        assertEquals("SESSAO_INVALIDA", resposta.getBody().get("erro"));
    }

    @Test
    public void importaLoteInteiroNaMesmaTransacao() {
        long id = criarUsuario("bk.importa");
        List<Map<String, String>> lote = List.of(itemValido("Gmail"), itemValido("Github"));

        ResponseEntity<Map> resposta = restTemplate.exchange("/backup", HttpMethod.POST, comTokenECorpo(id, "bk.importa", lote), Map.class);

        assertEquals(HttpStatus.OK, resposta.getStatusCode());
        assertEquals(2, resposta.getBody().get("credenciaisInseridas"));
        assertEquals(2, contaCredenciais(id));
    }

    @Test
    public void lotePartidoNaoGravaNada() {
        long id = criarUsuario("bk.partido");
        Map<String, String> invalido = new java.util.HashMap<>(itemValido("Github"));
        invalido.put("iv", "");
        List<Map<String, String>> lote = List.of(itemValido("Gmail"), invalido);

        ResponseEntity<Map> resposta = restTemplate.exchange("/backup", HttpMethod.POST, comTokenECorpo(id, "bk.partido", lote), Map.class);

        assertEquals(HttpStatus.BAD_REQUEST, resposta.getStatusCode());
        assertEquals("DADOS_INVALIDOS", resposta.getBody().get("erro"));
        assertEquals(0, contaCredenciais(id));
    }

    private Map<String, String> itemValido(String servico) {
        return Map.of("servico", servico, "usuarioServico", "eliseu@" + servico.toLowerCase(),
                "dadosCifrados", "dados-" + servico, "iv", "iv-" + servico);
    }

    private int contaCredenciais(long id) {
        return jdbc.queryForObject("SELECT COUNT(*) FROM credencial WHERE usuario_id = ?", Integer.class, id);
    }

    private HttpEntity<Object> comTokenECorpo(long id, String username, Object corpo) {
        HttpHeaders headers = new HttpHeaders();
        headers.setBearerAuth(jwtService.gerarToken(id, username));
        headers.setContentType(MediaType.APPLICATION_JSON);
        return new HttpEntity<>(corpo, headers);
    }

    private long criarUsuario(String username) {
        jdbc.update("INSERT INTO usuario (username, senha_mestra_hash, salt) VALUES (?, ?, ?)",
                username, "hash", "salt-" + username);
        return jdbc.queryForObject("SELECT id FROM usuario WHERE username = ?", Long.class, username);
    }

    private HttpEntity<Void> comToken(long id, String username) {
        HttpHeaders headers = new HttpHeaders();
        headers.setBearerAuth(jwtService.gerarToken(id, username));
        return new HttpEntity<>(headers);
    }
}
